// Generates test/types/large-config.test-d.ts: 200 permission names (up to 4 segments)
// and 40 roles, to keep an eye on type-checking cost. Run: node scripts/gen-type-bench.mjs
import { writeFileSync } from "node:fs";

const resources = Array.from({ length: 20 }, (_, i) => `resource${i}`);
const actions = ["create", "read", "update", "delete", "export"];
const perms = [];
for (const r of resources) {
  for (const a of actions) perms.push(`${r}.${a}`, `${r}.${a}.own`);
}
perms.length = 200;
const roles = Array.from({ length: 40 }, (_, i) => `role${i}`);

const list = (xs) => xs.map((x) => `    "${x}",`).join("\n");
writeFileSync(
  new URL("../test/types/large-config.test-d.ts", import.meta.url),
  `// Generated by scripts/gen-type-bench.mjs — ${perms.length} permissions, ${roles.length} roles.
import { expectTypeOf, it } from "vitest";
import { memoryAdapter } from "../../src/adapters/memory";
import { createPermissions } from "../../src/core/create-permissions";

const perms = createPermissions({
  adapter: memoryAdapter(),
  permissions: [
${list(perms)}
  ],
  roles: [
${list(roles)}
  ],
});

it("handles a large config", () => {
  perms.user(1).can("resource19.delete.own");
  perms.user(1).canAll(["resource0.create", "resource7.update"]);
  perms.role("role39").givePermission("resource3.*", "resource3.update.*", "*");
  perms.user(1).assignRole("role0", "role12");
  // @ts-expect-error misspelled permission
  perms.user(1).can("resource1.craete");
  expectTypeOf(perms.user(1).can("resource0.read")).toEqualTypeOf<Promise<boolean>>();
});
`,
);
